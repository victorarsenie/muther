# Installs the knowledge hook into Hermes, replacing the old hard-coded one.
# The old hook is backed up next to it with a timestamp.
param(
  [string]$HermesHome = 'D:\Hermes'
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$hookDir = Join-Path $HermesHome 'agent-hooks'
$hook = Join-Path $hookDir 'knowledge-index.py'
$adapter = Join-Path $repo 'adapters\hermes\knowledge-index.py'

if (-not (Test-Path $adapter)) { throw "adapter not found: $adapter" }
if (Test-Path $hook) {
  $backup = "$hook.bak-" + (Get-Date -Format 'yyyyMMdd-HHmmss')
  Copy-Item $hook $backup -Force
  Write-Host "backed up: $backup"
}

# A shim keeps one implementation: Hermes runs the repo's adapter directly.
$shim = @"
# Generated by E:\AI\jarvis\adapters\hermes\install.ps1
# The real hook lives in the repository so it can move with it.
import runpy
runpy.run_path(r"$adapter", run_name="__main__")
"@
Set-Content -Path $hook -Value $shim -Encoding utf8
Write-Host "installed shim: $hook"

# Verify it answers with JSON.
$payload = '{"hook_event_name":"pre_llm_call"}'
$out = $payload | & py -3 $hook 2>&1
if ($LASTEXITCODE -ne 0 -or -not $out) { throw "hook produced no output: $out" }
$json = $out | ConvertFrom-Json
Write-Host ("ok: context {0} chars" -f $json.context.Length)
